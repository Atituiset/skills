#!/usr/bin/env node
// gen-publish-pack.mjs — generate a project's PUBLISHING.md from disk truth.
//
// Zero dependencies; requires ffmpeg/ffprobe on PATH. Invoke via realpath (skill dirs
// may be symlinked). Everything except the prose blocks is computed, never hand-copied:
//   - final render  = newest mp4 in renders/ (stale renders are listed as a warning)
//   - chapters      = frame starts/durations from index.html + titles from STORYBOARD.md
//   - cover         = crop 1920:890 + pad to 1080 (cuts the caption band), dominant-color pad
//   - health probe  = flatness check of every frame close and transition seam
//   - credits/checklists = fonts, voice, repo URL, Bilibili + YouTube requirements
//
// Usage:
//   node <SKILL_DIR>/scripts/gen-publish-pack.mjs --project videos/<name>-zh
//     [--render <mp4>]  pick the render explicitly (default: newest in renders/)
//     [--cover-at <s>]  cover timestamp (default: 70% into frame 1)
//     [--pad-color HEX] cover pad color (default: dominant color of the cover frame)
//     [--out <file>]    output path (default: <project>/PUBLISHING.md)
//     [--force]         overwrite an existing hand-written PUBLISHING.md
//     [--no-cover]      skip cover generation
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative, resolve } from "node:path";

const GENERATED_MARKER = "<!-- generated by gen-publish-pack.mjs; safe to overwrite -->";

function fail(msg) {
  console.error(`gen-publish-pack: ${msg}`);
  process.exit(1);
}

// --- args ------------------------------------------------------------------
const argv = process.argv.slice(2);
const opts = { project: ".", out: null, render: null, coverAt: null, padColor: null, force: false, cover: true };
for (let i = 0; i < argv.length; i++) {
  const a = argv[i];
  if (a === "--project") opts.project = argv[++i];
  else if (a === "--out") opts.out = argv[++i];
  else if (a === "--render") opts.render = argv[++i];
  else if (a === "--cover-at") opts.coverAt = parseFloat(argv[++i]);
  else if (a === "--pad-color") opts.padColor = argv[++i].replace(/^#?/, "");
  else if (a === "--force") opts.force = true;
  else if (a === "--no-cover") opts.cover = false;
  else if (a === "--help" || a === "-h") opts.help = true;
  else fail(`unknown argument: ${a}`);
}
if (opts.help) {
  console.log(readFileSync(new URL(import.meta.url), "utf8").split("\n").filter((l) => l.startsWith("//")).map((l) => l.slice(3)).join("\n"));
  process.exit(0);
}
const project = resolve(opts.project);
if (!existsSync(join(project, "index.html")) && !existsSync(join(project, "scenes.json")))
  fail(`neither index.html nor scenes.json under ${project} — cannot locate the scene list`);

function run(cmd, args, { soft = false } = {}) {
  const r = spawnSync(cmd, args, { encoding: "buffer", maxBuffer: 64 * 1024 * 1024 });
  if (r.error) { if (soft) return null; fail(`${cmd}: ${r.error.message}`); }
  if (r.status !== 0) { if (soft) return null; fail(`${cmd} ${args.join(" ")}\n${String(r.stderr).slice(0, 800)}`); }
  return r.stdout;
}
const have = (cmd) => spawnSync(cmd, ["-version"], { stdio: "ignore" }).status === 0;
if (!have("ffmpeg") || !have("ffprobe")) fail("ffmpeg/ffprobe not found on PATH");

// --- scene starts + durations ------------------------------------------------------
// Two sources, because a video project is no longer one engine's project shape: an
// `index.html` with `data-start`/`data-duration` (HyperFrames), or a generated
// `scenes.json` (`[{n, start, dur, title, kicker}]`) from any frame-driven engine. Without the
// second, this tool only works on the engine it was written for — and the failure is a message
// pointing at index.html when the real problem is that the project is not that shape.
function parseScenes() {
  const json = join(project, "scenes.json");
  if (existsSync(json)) {
    return JSON.parse(readFileSync(json, "utf8")).map((s) => ({
      n: s.n, start: s.start, dur: s.dur, title: s.title, kicker: s.kicker,
    }));
  }
  return parseIndex();
}

function parseIndex() {
  const html = readFileSync(join(project, "index.html"), "utf8");
  const frames = new Map(); // n -> { start, dur }
  // the element id is `el-<prefix><NN>-<title>`; the prefix is optional because a project's
  // builder may namespace it (`el-f01-…`) — a strict `el-\d\d-` parses zero frames and fails
  // with a message that points at index.html rather than at the mismatch
  for (const tag of html.match(/<[^>]*id="el-[a-z]?\d\d-[^"]*"[^>]*>/g) ?? []) {
    const n = Number(tag.match(/id="el-[a-z]?(\d\d)-/)[1]);
    const f = frames.get(n) ?? {};
    const s = tag.match(/data-start="([\d.]+)"/);
    const d = tag.match(/data-duration="([\d.]+)"/);
    if (tag.includes("-voice")) { if (s) f.voiceStart = Number(s[1]); }
    else { if (s) f.start = Number(s[1]); if (d) f.dur = Number(d[1]); }
    frames.set(n, f);
  }
  const out = [...frames.entries()]
    .filter(([, f]) => (f.start ?? f.voiceStart) != null && f.dur != null)
    .map(([n, f]) => ({ n, start: f.start ?? f.voiceStart, dur: f.dur }))
    .sort((a, b) => a.n - b.n);
  if (out.length < 2) fail(`parsed only ${out.length} frames from index.html`);
  return out;
}

// --- STORYBOARD.md: frame titles -------------------------------------------
function parseTitles() {
  // a scene list that already carries titles (the engine knows them) needs no STORYBOARD.md
  if (existsSync(join(project, "scenes.json"))) {
    const t = new Map();
    for (const s of JSON.parse(readFileSync(join(project, "scenes.json"), "utf8"))) {
      if (s.title) t.set(s.n, s.title);
    }
    if (t.size) return t;
  }
  try {
    const md = readFileSync(join(project, "STORYBOARD.md"), "utf8");
    const titles = new Map();
    for (const m of md.matchAll(/^## Frame (\d+)\s*[—–-]\s*(.+)$/gm)) titles.set(Number(m[1]), m[2].trim());
    // …or a table, which is the richer of the two formats and the one a project that keeps
    // durations and beats alongside the title will already have:
    //   | # | title | kicker | beat | narration | frame | start |
    //   | 01 | 两秒钟 | ✱ 引入 | 0 | 14.66s | 15.56s | 0.00s |
    // Skip the header and separator rows by requiring a zero-padded frame number.
    if (titles.size === 0) {
      for (const m of md.matchAll(/^\|\s*(\d{1,2})\s*\|\s*([^|]+?)\s*\|.*$/gm)) {
        titles.set(Number(m[1]), m[2].trim());
      }
    }
    return titles;
  } catch {
    return new Map();
  }
}

// --- renders ----------------------------------------------------------------
function pickRender() {
  const dir = join(project, "renders");
  if (opts.render) {
    const p = resolve(opts.render);
    if (!existsSync(p)) fail(`render not found: ${p}`);
    return { path: p, all: [] };
  }
  if (!existsSync(dir)) fail(`no renders/ directory in ${project} — render first`);
  const all = readdirSync(dir)
    .filter((f) => f.endsWith(".mp4"))
    .map((f) => ({ path: join(dir, f), mtime: statSync(join(dir, f)).mtimeMs, size: statSync(join(dir, f)).size }))
    .sort((a, b) => b.mtime - a.mtime);
  if (all.length === 0) fail(`renders/ contains no .mp4 — render first`);
  return { path: all[0].path, all };
}

function probeDuration(path) {
  const out = run("ffprobe", ["-v", "error", "-show_entries", "format=duration,size", "-of", "csv=p=0", path]);
  const [dur, size] = String(out).trim().split(",");
  return { dur: parseFloat(dur), size: Number(size) };
}

// --- cover ------------------------------------------------------------------
function frameRaw(path, at, vf, soft = false) {
  return run("ffmpeg", ["-v", "error", "-ss", String(Math.max(0, at)), "-i", path, "-frames:v", "1", "-vf", vf, "-f", "rawvideo", "-pix_fmt", "rgb24", "-"], { soft });
}
function dominantColor(path, at) {
  const raw = frameRaw(path, at, "crop=w=1920:h=890:x=0:y=0,scale=16:9");
  if (raw.length < 16 * 9 * 3) fail("could not sample the cover frame");
  const counts = new Map();
  for (let i = 0; i + 2 < raw.length; i += 3) {
    const hex = [raw[i], raw[i + 1], raw[i + 2]].map((v) => v.toString(16).padStart(2, "0")).join("");
    counts.set(hex, (counts.get(hex) ?? 0) + 1);
  }
  return [...counts.entries()].sort((a, b) => b[1] - a[1])[0][0];
}
function makeCover(render, frames, lang) {
  const at = opts.coverAt ?? Math.round(frames[0].slot * 0.7 * 100) / 100;
  const color = opts.padColor ?? dominantColor(render, at);
  const out = join(project, "covers", `cover-${lang}.jpg`);
  mkdirSync(dirname(out), { recursive: true });
  if (existsSync(out)) return { path: out, at, color, kept: true };
  run("ffmpeg", ["-v", "error", "-ss", String(at), "-i", render, "-frames:v", "1",
    "-vf", `crop=w=1920:h=890:x=0:y=0,pad=w=1920:h=1080:x=0:y=0:color=0x${color}`,
    "-q:v", "2", "-y", out]);
  return { path: out, at, color, kept: false };
}

// --- seam/close probe -------------------------------------------------------
function probe(render, frames) {
  const moments = [
    { t: 0.35, what: "opening" },
    ...frames.map((f) => ({ t: f.start + f.slot, what: `close F${f.n}` })),
    ...frames.slice(1).map((f) => ({ t: f.start, what: `seam→F${f.n}` })),
  ];
  const anomalies = [];
  for (const m of moments) {
    const raw = frameRaw(render, Math.max(0, m.t - 0.15), "scale=64:36", true);
    if (!raw || raw.length < 64 * 36) { anomalies.push(`${m.what} @${m.t.toFixed(2)}s: no frame`); continue; }
    const v = [...raw.subarray(0, 64 * 36)];
    const mean = v.reduce((a, b) => a + b, 0) / v.length;
    const std = Math.sqrt(v.reduce((a, b) => a + (b - mean) ** 2, 0) / v.length);
    if (std < 3) anomalies.push(`${m.what} @${m.t.toFixed(2)}s: flat (std ${std.toFixed(1)})`);
  }
  return { total: moments.length, anomalies };
}

// --- misc facts -------------------------------------------------------------
function fmtTime(sec) {
  const s = Math.floor(sec);
  return `${String(Math.floor(s / 60)).padStart(2, "0")}:${String(s % 60).padStart(2, "0")}`;
}
function chaptersOf(frames, titles, renderDur) {
  const chapters = [];
  for (const f of frames) {
    const title = titles.get(f.n) ?? `Frame ${f.n}`;
    const prev = chapters[chapters.length - 1];
    // YouTube requires >=10s per chapter — fold a too-short tail into the previous one.
    if (prev && f.start - prev.at < 10) { prev.titles.push(title); continue; }
    chapters.push({ at: f.start, titles: [title] });
  }
  const last = chapters[chapters.length - 1];
  if (last && chapters.length > 1 && renderDur - last.at < 10) {
    chapters.pop();
    chapters[chapters.length - 1].titles.push(...last.titles);
  }
  return chapters;
}
function voiceOf() {
  // both spellings are in circulation: a `**Voice:** …` line, and YAML front matter
  // (`voice: edge-tts zh-CN-XiaoxiaoNeural rate +3%`), which is what the bilingual-video
  // scripts emit. Reading only the first leaves the credits block claiming "—".
  try {
    const md = ["SCRIPT.md", "script/SCRIPT.md"]
      .map((f) => join(project, f))
      .filter(existsSync)
      .map((f) => readFileSync(f, "utf8"))
      .join("\n");
    return md.match(/^\*\*Voice:\*\*\s*(.+)$/m)?.[1].trim()
        ?? md.match(/^voice:\s*(.+)$/m)?.[1].trim()
        ?? "—";
  } catch { return "—"; }
}
function fontsOf() {
  // `assets/fonts` (HyperFrames) and `public/fonts` (Remotion) are the same idea
  const dirs = [join(project, "assets", "fonts"), join(project, "public", "fonts")].filter(existsSync);
  if (!dirs.length) return [];
  try {
    return [...new Set(dirs.flatMap((d) => readdirSync(d)).filter((f) => /\.(woff2?|ttf|otf)$/.test(f))
      .map((f) => f.replace(/\.(woff2?|ttf|otf)$/, "").replace(/[-_](400|600|700|italic)$/, "")))];
  } catch { return []; }
}
function repoUrlOf() {
  const r = spawnSync("git", ["-C", project, "remote", "get-url", "origin"], { encoding: "utf8" });
  return r.status === 0 ? r.stdout.trim().replace(/\.git$/, "") : null;
}
const lang = /-(zh|en)$/.test(basename(project)) ? basename(project).slice(-2) : "zh";

// --- build ------------------------------------------------------------------
const frames = parseScenes();
const titles = parseTitles();
const { path: render, all: renderList } = pickRender();
const { dur, size } = probeDuration(render);
// data-duration includes the 0.5s transition overlap — the timeline slot is the gap to the next start.
frames.forEach((f, i) => {
  const next = frames[i + 1];
  f.slot = next ? next.start - f.start : Math.min(f.dur, dur - f.start);
});
const chapters = chaptersOf(frames, titles, dur);
const missing = frames.filter((f) => !titles.has(f.n));
const probeResult = probe(render, frames);
const cover = opts.cover ? makeCover(render, frames, lang) : null;
const voice = voiceOf();
const fonts = fontsOf();
const repo = repoUrlOf();
const frameTotal = frames.reduce((a, f) => a + f.slot, 0);
const name = basename(project);

const outPath = resolve(opts.out ?? join(project, "PUBLISHING.md"));

// The prose blocks are the ONE thing here a person writes, and the reason to re-run this
// script at all is to recompute everything else after a re-render. So the filled text is
// carried across: each `<!-- FILL: … -->` … `<!-- /FILL -->` pair is looked up by its opening
// comment and re-emitted verbatim. Without this, every regeneration silently deletes the
// description, the lede and the titles — which is the whole reason the file exists.
const prose = new Map();
if (existsSync(outPath)) {
  const existing = readFileSync(outPath, "utf8");
  if (!existing.includes(GENERATED_MARKER))
    fail(`${outPath} exists and was not generated by this script — use --out <file> or --force`);
  for (const m of existing.matchAll(/<!-- FILL:([\s\S]*?)-->\n([\s\S]*?)<!-- \/FILL -->/g)) {
    const key = m[1].trim();
    if (!prose.has(key)) prose.set(key, m[2].replace(/^\n+/, "").replace(/\n+$/, ""));
  }
}
const fill = (key) => {
  const body = prose.get(key);
  return `<!-- FILL:${key} -->\n${body ? body : `<!-- ${key} -->`}\n<!-- /FILL -->`;
};

const chapterBlock = chapters.map((c) => `${fmtTime(c.at)} ${c.titles.join(" / ")}`).join("\n");
const staleWarning = renderList.length > 1
  ? `\n> ⚠ ${renderList.length} renders on disk — **verify this is the final cut** before uploading:\n` +
    renderList.map((r) => `> - \`${relative(project, r.path)}\` — ${(r.size / 1e6).toFixed(1)} MB, ${new Date(r.mtime).toISOString().slice(0, 16).replace("T", " ")}${r.path === render ? " ← selected" : ""}`).join("\n") + "\n"
  : "";

const md = `# PUBLISHING — ${name}

${GENERATED_MARKER}
> Generated ${new Date().toISOString().slice(0, 10)} from \`index.html\` + \`STORYBOARD.md\` + the newest render.
> Re-running overwrites the \`<!-- FILL -->\` prose blocks below — everything else is recomputed.${staleWarning}

## Deliverable

| Item | Value |
| --- | --- |
| Video | \`${relative(project, render)}\` |
| Duration | ${fmtTime(dur)} (${dur.toFixed(2)}s) |
| Size | ${(size / 1e6).toFixed(1)} MB |
| Cover | ${cover ? `\`${relative(project, cover.path)}\`` + (cover.kept ? " (kept — existing file)" : "") + ` — crop 1920:890 + pad #${cover.color.toUpperCase()}, cover-at ${cover.at}s` : "— (--no-cover)"} |
| Voice | ${voice} (**synthetic voice**) |
| Captions | burned in (\`compositions/captions.html\`) |
| Index total | ${frameTotal.toFixed(2)}s across ${frames.length} frames |
${Math.abs(frameTotal - dur) > 1 ? `\n> ⚠ index total (${frameTotal.toFixed(1)}s) and render duration (${dur.toFixed(1)}s) differ by >1s — confirm the render matches this index.\n` : ""}
## Title / lede

${fill("2–4 sentences in the video's language")}

${fill("opening lede — the viewer's pain point + what the film settles")}

${fill("1–2 title options")}

## Chapter timeline

${chapterBlock}

## Bilibili

- 分区：**科技 → 计算机技术** · 投稿类型：**原创**
- 描述：

\`\`\`
${fill("2–4 sentence description in the video's language")}

⏱ 章节
${chapterBlock}

🧮 仓库
${repo ?? "<!-- FILL: repo URL -->"}

—— 素材与致谢 ——
· 配音：${voice}，AI 合成语音
· 合成与渲染：HyperFrames（本地渲染）${fonts.length ? `\n· 字体（SIL Open Font License）：${fonts.join("、")}` : ""}
· 画面：全部为原创动态图形，无第三方素材

⚠️ 本片旁白为 AI 合成语音，内容与画面均为原创。
\`\`\`

## YouTube

- 分类：**Science & Technology** · 勾选 **Altered content**（合成语音披露）
- Chapters（首条 0:00、每条 ≥10s — 自动满足）：

\`\`\`
${chapterBlock}
\`\`\`

- 描述：

\`\`\`
${fill("same lede as above (translate if the video language differs)")}

⏱ Chapters
${chapterBlock}

🧮 Calculator repo
${repo ?? "<!-- FILL: repo URL -->"}

—— Credits ——
· Voice: ${voice}, a synthetic voice
· Composition & render: HyperFrames (local render)${fonts.length ? `\n· Fonts (SIL Open Font License): ${fonts.join(", ")}` : ""}
· Visuals: all-original motion graphics, no third-party assets

⚠️ This video uses a synthetic voice. Content and visuals are original.
\`\`\`

> Chapter titles come from \`STORYBOARD.md\` in the video's own language — translate them for YouTube if the upload language differs.

## Pre-upload checklist (human)

- [ ] **Listen to the narration once** (mixed zh/en terms especially) — the model cannot hear its own audio (pitfall 26)
- [ ] Seam/close probe: ${probeResult.anomalies.length === 0 ? `**${probeResult.total}/${probeResult.total} moments OK** (no blank/flat frames)` : `**${probeResult.anomalies.length} anomalies:**\n  - ${probeResult.anomalies.join("\n  - ")}`}
- [ ] Cover readable at mobile thumbnail size; re-run with \`--cover-at <s>\` to re-pick the moment (existing cover must be deleted first)
- [ ] Final render confirmed newest (see warning above if several)
- [ ] Opening skeleton lands ≤0.45s after upload spot-check
`;

writeFileSync(outPath, md, "utf8");
console.log(`gen-publish-pack: wrote ${outPath}`);
console.log(`  render   ${render} (${fmtTime(dur)}, ${(size / 1e6).toFixed(1)} MB)`);
console.log(`  chapters ${chapters.length} from ${frames.length} frames${missing.length ? ` (no title for F${missing.map((f) => f.n).join(", F")})` : ""}`);
console.log(`  cover    ${cover ? `${cover.path} @${cover.at}s ${cover.kept ? "(kept)" : ""}` : "skipped"}`);
console.log(`  probe    ${probeResult.total} moments, ${probeResult.anomalies.length} anomalies`);
for (const a of probeResult.anomalies) console.log(`    ⚠ ${a}`);
